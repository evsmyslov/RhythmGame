function makeMap({ id, title, bpm, difficulty, bars, phrases }) {
  const beat = 60 / bpm;
  const notes = [];
  const accents = [];
  const climaxes = [];
  for (const [bar, phrase] of bars.entries()) {
    const timeAt = step => (bar * 4 + step / 4) * beat;
    for (let pulse = 0; pulse < 4; pulse++) {
      accents.push({ time: timeAt(pulse * 4), strength: pulse === 0 ? .95 : pulse === 2 ? .74 : .50 });
    }
    if (bar > 0 && bar % 8 === 0) climaxes.push(timeAt(0));
    for (const [step, lane, checkpoints] of phrases[phrase] || []) {
      const time = timeAt(step);
      const note = { time, lane };
      if (checkpoints) {
        note.path = [{ time, lane }, ...checkpoints.map(([at, nextLane]) => ({ time: timeAt(at), lane: nextLane }))];
      }
      notes.push(note);
    }
  }
  return {
    id, title, bpm, difficulty, duration: bars.length * 4 * beat + 1.8,
    url: "./assets/tracks/" + id + ".mp3", notes, accents, climaxes, brightness: .26 + difficulty * .1
  };
}

export const catalog = scores.map(makeMap);

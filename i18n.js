const storageKey = "pulsewake-language";
let selected = globalThis.navigator?.language?.toLowerCase().startsWith("en") ? "en" : "ru";
try {
  const saved = localStorage.getItem(storageKey);
  if (saved === "ru" || saved === "en") selected = saved;
} catch { /* The language can still be changed when storage is unavailable. */ }

export const language = () => selected;
export const t = (ru, en) => selected === "ru" ? ru : (en ?? (Object.hasOwn(english, ru) ? english[ru] : ru));

const numbers = { ru: new Intl.NumberFormat("ru"), en: new Intl.NumberFormat("en") };
export const formatNumber = value => numbers[selected].format(value);

export function initLanguage() {
  const button = document.getElementById("language-button");
  const bindings = [];
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const original = node.data;
    const ru = original.trim();
    const en = node.parentElement?.dataset.en ?? english[ru];
    if (!ru || typeof en !== "string") continue;
    bindings.push(() => {
      if (node.isConnected) node.data = original.replace(ru, () => t(ru, en));
    });
  }

  for (const attr of ["aria-label", "title", "placeholder", "content"]) {
    for (const node of document.querySelectorAll("[" + attr + "]")) {
      const ru = node.getAttribute(attr);
      const en = node.getAttribute("data-en-" + attr) ?? english[ru];
      if (typeof en !== "string") continue;
      bindings.push(() => {
        const current = node.getAttribute(attr);
        if (current === ru || current === en) node.setAttribute(attr, t(ru, en));
      });
    }
  }

  const refresh = () => {
    document.documentElement.lang = selected;
    for (const render of bindings) render();
    if (button) {
      button.textContent = t("EN", "RU");
      button.setAttribute("aria-label", t("Переключить на английский", "Switch to Russian"));
      button.title = t("English", "Русский");
    }
  };
  refresh();
  button?.addEventListener("click", () => {
    const error = document.getElementById("source-error");
    const status = document.getElementById("status-text");
    for (const node of [error, status]) {
      if (!node?.textContent) continue;
      const translated = selected === "ru" ? english[node.textContent] :
        Object.keys(english).find(ru => english[ru] === node.textContent);
      if (typeof translated === "string") node.textContent = translated;
    }
    selected = selected === "ru" ? "en" : "ru";
    try { localStorage.setItem(storageKey, selected); } catch { /* Apply for this visit. */ }
    refresh();
    document.dispatchEvent(new Event("languagechange"));
  });
}
